import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
const root = new URL("../", import.meta.url).pathname;
// The native WebView ships one offline bundle. Avoid shipping every Shiki grammar.
const languages = [
  "typescript",
  "tsx",
  "javascript",
  "jsx",
  "json",
  "css",
  "html",
  "markdown",
  "python",
  "rust",
  "go",
  "bash",
  "yaml",
  "swift",
  "kotlin",
  "sql",
  "diff",
];
const langSource =
  languages
    .map((lang, i) => `import l${i} from '@shikijs/langs/${lang}';`)
    .join("\n") +
  `\nexport const bundledLanguages={${languages.map((lang, i) => `'${lang}':async()=>({default:l${i}})`).join(",")}};`;
const result = await build({
  entryPoints: [path.join(root, "packages/native-viewer/src/entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  minify: true,
  target: ["es2022"],
  define: { "process.env.NODE_ENV": '"production"' },
  plugins: [
    {
      name: "native-grammars",
      setup(b) {
        b.onResolve({ filter: /^shiki\/langs$/ }, () => ({
          path: "native-langs",
          namespace: "native",
        }));
        b.onLoad({ filter: /.*/, namespace: "native" }, () => ({
          contents: langSource,
          resolveDir: root,
        }));
      },
    },
  ],
});
const js = result.outputFiles[0].text;
const sans = await readFile(
  path.join(
    root,
    "node_modules/@fontsource/geist/files/geist-latin-400-normal.woff2",
  ),
);
const mono = await readFile(
  path.join(
    root,
    "node_modules/@fontsource/geist-mono/files/geist-mono-latin-400-normal.woff2",
  ),
);
await mkdir(path.join(root, "apps/mobile/generated"), { recursive: true });
await writeFile(
  path.join(root, "apps/mobile/generated/viewer.ts"),
  `// Generated by npm run build:viewer. No network dependencies.\nexport const viewerScript=${JSON.stringify(js)};\nexport const sansFont=${JSON.stringify(sans.toString("base64"))};\nexport const monoFont=${JSON.stringify(mono.toString("base64"))};\n`,
);
console.log(
  `Native viewer: ${(js.length / 1024 / 1024).toFixed(2)} MB, ${languages.length} bundled grammars, embedded Geist fonts.`,
);
